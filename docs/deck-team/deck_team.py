FIELDS = ("Τι κάνει", "Τι λύνει", "Πώς γίνεται")

def feature(eb, head, does, solves, how, image=None, flip=False):
    """Μία λειτουργία: τίτλος, τρεις γραμμές, μία οθόνη."""
    s = slide()
    if image:
        tx = 7.35 if flip else 0.95
        ix = 0.62 if flip else 6.85
        tw = 4.95
        fit_image(s, os.path.join(SHOTS, image), ix, 1.28, 5.86, 4.95)
    else:
        tx, tw = 0.95, 11.4

    eyebrow(s, tx, 0.82, eb)
    y = 1.22
    tf = box(s, tx, y, tw, 1.5)
    para(tf, head, 25, INK, bold=True, first=True, line=1.08)
    y += 0.44 * wrapped_lines(head, int(tw / 0.175)) + 0.30

    chars = int(tw / 0.0773)
    for label, text in zip(FIELDS, (does, solves, how)):
        tf = box(s, tx, y, tw, 0.26)
        para(tf, label, 9.5, RUST, bold=True, first=True, spacing=1.0)
        y += 0.255
        tf = box(s, tx, y, tw, 1.6)
        para(tf, text, 11.5, SOFT, first=True, line=1.34)
        y += 0.205 * wrapped_lines(text, chars) + 0.30

    stamp(s)
    return s


def section(n, title, blurb):
    """Χωριστική διαφάνεια."""
    s = slide(NAVY)
