# --- helpers -------------------------------------------------------------

def slide(bg=PAPER):
    s = prs.slides.add_slide(BLANK)
    r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
    r.fill.solid(); r.fill.fore_color.rgb = bg
    r.line.fill.background(); r.shadow.inherit = False
    return s


def box(s, x, y, w, h):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    return tf


def para(tf, text, size, color, bold=False, space_after=0, space_before=0,
         first=False, line=None, spacing=None):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.space_after = Pt(space_after)
    p.space_before = Pt(space_before)
    if line:
        p.line_spacing = line
    run = p.add_run()
    run.text = text
    f = run.font
    f.name = FONT
    f.size = Pt(size)
    f.bold = bold
    f.color.rgb = color
    if spacing is not None:
        rPr = run._r.get_or_add_rPr()
        rPr.set("spc", str(int(spacing * 100)))
    return p


def rule(s, x, y, w=1.15, h=0.055, color=RUST):
    r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    r.fill.solid(); r.fill.fore_color.rgb = color
    r.line.fill.background(); r.shadow.inherit = False
    return r


def fit_image(s, path, x, y, w, h, border=True):
    """Ολόκληρη η οθόνη μέσα στο πλαίσιο, κεντραρισμένη.

    Το `cover` έκοβε αριστερά και δεξιά, και σε στιγμιότυπο του πίνακα αυτό
    σημαίνει μισό πλαϊνό μενού — διαβάζεται σαν χαλασμένη εικόνα, όχι σαν
    κάδρο. Εδώ η εικόνα μπαίνει ολόκληρη και ό,τι περισσεύει είναι χώρος.
    """
    iw, ih = Image.open(path).size
    img_a, box_a = iw / ih, w / h
    if img_a > box_a:                      # πιο φαρδιά: το πλάτος δεσμεύει
        dw, dh = w, w / img_a
    else:                                  # πιο ψηλή: το ύψος δεσμεύει
        dh, dw = h, h * img_a
    pic = s.shapes.add_picture(path, Inches(x + (w - dw) / 2), Inches(y + (h - dh) / 2),
                               Inches(dw), Inches(dh))
    if border:
        pic.line.color.rgb = RULE
        pic.line.width = Pt(1)
    return pic


def eyebrow(s, x, y, text, color=RUST):
    # Ποτέ κεφαλαία στα ελληνικά (I18N-2): χάνονται οι τόνοι και το τελικό σίγμα.
    tf = box(s, x, y, 8, 0.3)
    para(tf, text, 10.5, color, bold=True, first=True, spacing=1.1)


N = [0]

def stamp(s):
    N[0] += 1
    tf = box(s, W - 1.15, H - 0.52, 0.7, 0.3)
    p = para(tf, f"{N[0]:02d}", 9.5, FAINT, first=True)
    p.alignment = PP_ALIGN.RIGHT


def wrapped_lines(text, chars):
    """Πόσες γραμμές πιάνει ένα κείμενο σε δεδομένο πλάτος, κατά προσέγγιση."""
    lines, n = 1, 0
    for word in text.split():
        add = len(word) + (1 if n else 0)
        if n + add > chars:
            lines += 1
            n = len(word)
        else:
            n += add
    return lines


