# --- helpers -------------------------------------------------------------

def slide(bg=PAPER):
    s = prs.slides.add_slide(BLANK)
    r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
    r.fill.solid(); r.fill.fore_color.rgb = bg
    r.line.fill.background(); r.shadow.inherit = False
    return s


def box(s, x, y, w, h):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    return tf


def para(tf, text, size, color, bold=False, space_after=0, space_before=0,
         first=False, line=None, caps=False, spacing=None):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.space_after = Pt(space_after)
    p.space_before = Pt(space_before)
    if line:
        p.line_spacing = line
    run = p.add_run()
    run.text = text.upper() if caps else text
    f = run.font
    f.name = FONT
    f.size = Pt(size)
    f.bold = bold
    f.color.rgb = color
    if spacing is not None:
        # γράμμα-γράμμα απόσταση για τα μικρά κεφαλαία
        rPr = run._r.get_or_add_rPr()
        rPr.set("spc", str(int(spacing * 100)))
    return p


def rule(s, x, y, w=1.15, h=0.055, color=RUST):
    r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    r.fill.solid(); r.fill.fore_color.rgb = color
    r.line.fill.background(); r.shadow.inherit = False
    return r


def cover_image(s, path, x, y, w, h, border=True):
    """object-fit: cover — κόβει, δεν παραμορφώνει. Κρατά την κορυφή."""
    iw, ih = Image.open(path).size
    img_a, box_a = iw / ih, w / h
    pic = s.shapes.add_picture(path, Inches(x), Inches(y), Inches(w), Inches(h))
    if img_a > box_a:                     # πιο φαρδιά: κόψε αριστερά/δεξιά
        keep = (ih * box_a) / iw
        pic.crop_left = pic.crop_right = (1 - keep) / 2
    else:                                 # πιο ψηλή: κράτα την κορυφή
        keep = (iw / box_a) / ih
        pic.crop_top = 0.0
        pic.crop_bottom = 1 - keep
    if border:
        pic.line.color.rgb = RULE
        pic.line.width = Pt(1)
    return pic


def eyebrow(s, x, y, text, color=RUST):
    # Ποτέ κεφαλαία στα ελληνικά: τα κεφαλαία χάνουν τους τόνους και κάθε
    # μηχανή τα κόβει αλλιώς. Η ιεραρχία βγαίνει από βάρος και αραίωση.
    tf = box(s, x, y, 8, 0.3)
    para(tf, text, 11, color, bold=True, first=True, spacing=1.1)


def headline(s, x, y, text, w=5.4, size=34, color=INK):
    tf = box(s, x, y, w, 2.2)
    para(tf, text, size, color, bold=True, first=True, line=1.06)


def body(s, x, y, text, w=5.4, size=14.5, color=SOFT, line=1.42):
    tf = box(s, x, y, w, 3.2)
    para(tf, text, size, color, first=True, line=line)
    return tf


def points(s, x, y, items, w=5.4, size=13.5, gap=13, strong=INK, soft=SOFT):
    """Γραμμές με μικρό τετράγωνο αντί για τελείες."""
    tf = box(s, x, y, w, 4.2)
    for i, (title, rest) in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        p.line_spacing = 1.34
        r1 = p.add_run(); r1.text = "▪  "
        r1.font.name = FONT; r1.font.size = Pt(size); r1.font.color.rgb = RUST; r1.font.bold = True
        r2 = p.add_run(); r2.text = title
        r2.font.name = FONT; r2.font.size = Pt(size); r2.font.bold = True; r2.font.color.rgb = strong
        if rest:
            r3 = p.add_run(); r3.text = "  " + rest
            r3.font.name = FONT; r3.font.size = Pt(size); r3.font.color.rgb = soft
    return tf


def number(s, n, color=FAINT):
    tf = box(s, W - 1.15, H - 0.62, 0.7, 0.3)
    p = para(tf, f"{n:02d}", 10, color, first=True)
    p.alignment = PP_ALIGN.RIGHT


N = [0]

def stamp(s):
    N[0] += 1
    number(s, N[0])


