def shot_slide(eb, head, text, items, image, bg=PAPER, flip=False):
    s = slide(bg)
    tx = 7.75 if flip else 1.05
    ix = 1.05 if flip else 6.62
    eyebrow(s, tx, 0.95, eb)
    headline(s, tx, 1.42, head, w=4.55, size=27)
